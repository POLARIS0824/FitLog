package com.example.fitlog.util.log

/**
 * 日志级别。
 *
 * 仅四档，不设 VERBOSE（本项目用不上更细的分层）：枚举序数即优先级，
 * 可直接用比较运算判断"是否达到输出门槛"。
 *
 * 级别约定（全项目统一）：
 * - [DEBUG]：调试细节，仅 debug 构建落盘（AI 请求/响应正文、匹配降级过程等）
 * - [INFO]：功能链路里程碑（AI 往返元数据、导入各阶段汇总、页面导航、生命周期）
 * - [WARN]：降级警告——功能未中断但偏离预期（guard 降级、匹配落空、缓存失效）
 * - [ERROR]：操作失败且用户可感知（写入失败、AI 请求失败）；崩溃以 [ERROR] + [CRASH] 前缀表达
 */
enum class LogLevel(val label: String) {

    /** 调试细节：正式构建的各 sink 会按自身门槛过滤掉。 */
    DEBUG("D"),

    /** 常规事件：诊断"做了什么"。 */
    INFO("I"),

    /** 降级警告：诊断"哪里不对劲但兜住了"。 */
    WARN("W"),

    /** 错误：诊断"什么失败了"。 */
    ERROR("E"),
}
